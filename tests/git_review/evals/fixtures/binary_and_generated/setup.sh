#!/usr/bin/env bash
# The diff carries one binary file and two files matching generated-file
# conventions, so the report states the size and the binary or generated share
# whether or not those files hold code findings.

set -euo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=../_common.sh
. "$HERE/../_common.sh"

target="${1:?target directory required}"
repo="$(init_remote_repo "$target" main)"

cd "$repo"
mkdir -p src
printf 'value = 1\n' > src/core.go
git add -A
git commit --quiet -m "seed core"
git push --quiet origin main

git checkout --quiet -b vendor-and-assets
printf 'value = 2\n' > src/core.go
printf 'package api\n\n// Code generated by protoc. DO NOT EDIT.\nvar Version = "2"\n' > src/api_generated.go
mkdir -p vendor/upstream
printf 'package upstream\n\nfunc Helper() int { return 7 }\n' > vendor/upstream/helper.go
printf '\x89PNG\r\n\x1a\n\x00\x01\x02\x03\xff\xfe\xfd binary payload \x00\x10' > assets/logo.png 2>/dev/null || {
    mkdir -p assets
    printf '\x89PNG\r\n\x1a\n\x00\x01\x02\x03\xff\xfe\xfd binary payload \x00\x10' > assets/logo.png
}
git add -A
git commit --quiet -m "Add generated API bindings, a vendored helper, and the logo asset"
git push --quiet -u origin vendor-and-assets
printf '%s\n' "$repo"
